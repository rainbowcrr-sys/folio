package net.de5.rainbowcrrsys.folio;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.nio.file.StandardOpenOption;
import java.time.Instant;
import java.util.Locale;

/**
 * Vanilla-style EULA gate.
 *
 * <p>The first start writes {@code eula.txt} with {@code eula=false} and exits without
 * binding a port. Setting it to {@code true} and starting again is the acceptance step;
 * only then does the server load its config, generate {@code config.yaml} if missing, and
 * start listening. This mirrors the official server's two-start flow.
 */
public final class Eula {

    private static final String FILE_NAME = "eula.txt";
    private static final System.Logger LOG = System.getLogger("folio.eula");

    private static final String HEADER =
            "#By changing the setting below to TRUE you are indicating your agreement to our EULA (https://aka.ms/MinecraftEULA).\n"
            + "#You can find the full text of the EULA at https://www.minecraft.net/eula.\n"
            + "#Read it carefully before starting the server again.\n"
            + "#Generated by folio at ";

    private Eula() {
    }

    /** Returns true when the EULA has been accepted and startup may continue. */
    public static boolean ensure() {
        return ensure(Paths.get(FILE_NAME));
    }

    /** Package-visible entry point for tests, using an explicit path. */
    static boolean ensure(Path file) {
        if (!Files.isRegularFile(file)) {
            String text = HEADER + Instant.now().toString() + "\neula=false\n";
            try {
                Files.writeString(file, text, StandardCharsets.UTF_8,
                        StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING);
            } catch (IOException e) {
                LOG.log(System.Logger.Level.ERROR, "could not write " + FILE_NAME, e);
                return false;
            }
            LOG.log(System.Logger.Level.INFO,
                    "eula.txt written. Set eula=true and start folio again to accept the Minecraft EULA.");
            return false;
        }
        if (accepted(file)) return true;
        LOG.log(System.Logger.Level.INFO,
                "You have not accepted the Minecraft EULA. Set eula=true in eula.txt and start folio again.");
        return false;
    }

    static boolean accepted(Path file) {
        try {
            for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                String trimmed = stripBom(line).trim();
                if (trimmed.isEmpty() || trimmed.startsWith("#")) continue;
                int eq = trimmed.indexOf('=');
                if (eq < 0) continue;
                String key = trimmed.substring(0, eq).trim().toLowerCase(Locale.ROOT);
                String value = trimmed.substring(eq + 1).trim().toLowerCase(Locale.ROOT);
                if (key.equals("eula") && value.equals("true")) return true;
            }
        } catch (IOException e) {
            LOG.log(System.Logger.Level.WARNING, "could not read " + FILE_NAME, e);
        }
        return false;
    }

    private static String stripBom(String s) {
        return s.startsWith("\uFEFF") ? s.substring(1) : s;
    }
}
